def write(target, props):
    path = os.path.join("versions", target)
    os.makedirs(path, exist_ok=True)
    with open(os.path.join(path, "gradle.properties"), "w") as out:
        out.write("# Generated by tools/gen_targets.py\n")
        for key, value in props:
            out.write(f"{key}={value}\n")

for mc, range_, fabric_range, java, pack, forge, forge_major, fabric_api, neo in LINES:
    common = [("minecraft_version", mc), ("minecraft_range", range_), ("java_version", java), ("pack_format", pack)]
    write(f"{mc}-fabric", [("loom.platform", "fabric")] + common + [
        ("fabric_minecraft_range", fabric_range), ("fabric_loader_version", FABRIC_LOADER), ("fabric_api_version", fabric_api)])
    write(f"{mc}-forge", [("loom.platform", "forge")] + common + [("forge_version", forge), ("loader_range", forge_major)])
    if neo:
        neo_line = ".".join(neo.split(".")[:2])
        extra = [("neoforge_version", neo), ("neoforge_range", f"[{neo_line},)")]
        if mc == "1.20.4":
            extra.append(("neoforge_legacy_toml", "true"))
        write(f"{mc}-neoforge", [("loom.platform", "neoforge")] + common + extra)
